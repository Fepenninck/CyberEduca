const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const source = fs.readFileSync(path.join(__dirname, '../lib/admin-collection.ts'), 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText
const moduleObject = { exports: {} }
new Function('exports', 'module', compiled)(moduleObject.exports, moduleObject)
const { paginarRegistros, selecionarRegistros, ADMIN_PAGE_SIZE } = moduleObject.exports
assert.equal(ADMIN_PAGE_SIZE, 4)
const registros = Array.from({length:11}, (_, id) => ({id, nome: `Aula ${id + 1}`, status: id % 2 ? 'ATIVAS' : 'INATIVAS'}))
const paginas = [1,2,3].map(pagina => paginarRegistros(registros, pagina))
assert.deepEqual(paginas.map(pagina => pagina.visiveis.length), [4,4,3])
assert.deepEqual(paginas.flatMap(pagina => pagina.visiveis.map(item => item.id)), registros.map(item => item.id))
assert.equal(paginarRegistros(registros, 99).pagina, 3)
assert.equal(paginarRegistros(registros.slice(0,8), 3).pagina, 2)
assert.equal(paginarRegistros(registros, -1).pagina, 1)
assert.deepEqual(paginarRegistros([], 3), { pagina:1,totalPaginas:1,visiveis:[],inicio:0,fim:0 })
const ativas = selecionarRegistros(registros, item => item.nome, '', 'ATIVAS', item => item.status)
assert.equal(ativas.length, 5)
assert.ok(ativas.every(item => item.status === 'ATIVAS'))
assert.equal(paginarRegistros(ativas, 2).visiveis.length, 1)
assert.equal(selecionarRegistros(registros, item => item.nome, 'Aula 2', 'ATIVAS', item => item.status).length, 1)
assert.equal(selecionarRegistros(registros, item => item.nome, 'Aula 2', 'INATIVAS', item => item.status).length, 0)
assert.equal(selecionarRegistros(registros, item => item.nome, '', 'TODOS', item => item.status).length, 11)
assert.equal(selecionarRegistros([{nome:'Proteção de dados'}], item => item.nome, '  PROTECAO ').length, 1)
console.log('Paginação: limite de 4, navegação, filtros, acentos e exclusão da última página verificados.')
