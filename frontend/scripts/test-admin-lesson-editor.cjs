const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const cache = new Map()
function carregar(relative) {
  const arquivo = path.resolve(__dirname, relative)
  if (cache.has(arquivo)) return cache.get(arquivo)
  const source = fs.readFileSync(arquivo, 'utf8')
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText
  const moduleObject = { exports: {} }
  const importar = name => name === '@/lib/admin-lesson-editor' ? carregar('../lib/admin-lesson-editor.ts') : name === './lesson-material-editor' ? carregar('../components/admin/lesson-material-editor.tsx') : require(name)
  new Function('require', 'module', 'exports', compiled)(importar, moduleObject, moduleObject.exports)
  cache.set(arquivo, moduleObject.exports)
  return moduleObject.exports
}
const { carregarConteudoAula, serializarMaterialAula, validarMaterialAula, resumoConteudoAula, urlEditorialValida } = carregar('../lib/admin-lesson-editor.ts')
const { parseLessonMaterial } = carregar('../lib/lesson-material.ts')
const original = { format:'cybereduca-lesson-v1', title:'Título', level:'BASICO', concept:'Explicação principal da aula.', practice:'Observe o exemplo.', source:'https://example.com/fonte', sourceTitle:'Referência', objectives:['Primeiro objetivo'], caseStudy:'Exemplo prático.', expected:'Metadado legado', video:{title:'Vídeo',url:'https://example.com/video.mp4',source:'https://example.com/video',prompt:'Observe.',credit:'Crédito preservado'}, diagram:{title:'Etapas',nodes:['A','B','C'],notes:['','',''],caption:'Legenda'}, glossary:[{term:'Termo',meaning:'Definição'}], readings:[{title:'Leitura',url:'https://example.com/leitura',task:'Leia.'}], introductory:{step:1,image:{src:'/imagem.png',alt:'Descrição',caption:'Legenda'},checkpoint:{question:'Qual opção?',options:['A','B'],correct:0,explanation:'Explicação'},takeaway:'Lembrete'}, metadadoExtra:{preservar:true} }
const carregado = carregarConteudoAula('  ' + JSON.stringify(original) + '\n')
assert.equal(carregado.modo, 'estruturado')
assert.deepEqual(JSON.parse(serializarMaterialAula(carregado.material, 'Título', 'BASICO')), original)
assert.equal(validarMaterialAula(carregado.material), null)
const alterado = JSON.parse(serializarMaterialAula({...carregado.material, concept:'Texto atualizado'}, 'Novo título', 'AVANCADO'))
assert.equal(alterado.title, 'Novo título')
assert.equal(alterado.level, 'AVANCADO')
assert.deepEqual(alterado.video, original.video)
assert.deepEqual(alterado.introductory, original.introductory)
assert.deepEqual(alterado.metadadoExtra, original.metadadoExtra)
assert.equal(parseLessonMaterial(JSON.stringify(alterado)).concept, 'Texto atualizado')
assert.equal(carregarConteudoAula('Texto de uma aula antiga.').modo, 'texto')
assert.equal(carregarConteudoAula('{"format":"cybereduca-lesson-v1", quebrado}').modo, 'invalido')
assert.equal(carregarConteudoAula('').modo, 'estruturado')
assert.equal(resumoConteudoAula(JSON.stringify(original)), original.concept)
assert.equal(urlEditorialValida('javascript:alert(1)'), false)
assert.equal(urlEditorialValida('/imagens/aula.png', true), true)
assert.equal(urlEditorialValida('//example.com/imagem', true), false)
assert.ok(validarMaterialAula({...original, source:'javascript:alert(1)'}))
assert.ok(validarMaterialAula({...original, concept:'  '}))
const { FormularioAula } = carregar('../components/admin/formulario-aula.tsx')
const html = renderToStaticMarkup(React.createElement(FormularioAula, { trilhas:[{id:'trilha',titulo:'Trilha',nivel:'BASICO'}],aulasExistentes:[],initialValues:{id:'aula',titulo:original.title,conteudo:JSON.stringify(original),trilhaId:'trilha',ordem:1},onSubmit:async()=>{} }))
assert.ok(html.includes('Explicação principal da aula.'))
