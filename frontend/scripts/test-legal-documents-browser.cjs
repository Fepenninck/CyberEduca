const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { chromium } = require('playwright-core')
const { PrismaClient } = require('../../backend/node_modules/@prisma/client')
const { JwtService } = require('../../backend/node_modules/@nestjs/jwt')

async function main() {
  const baseURL = process.env.PRIVACY_TEST_URL || 'http://localhost:3301'
  const connection = new URL(process.env.DATABASE_URL || '')
  if (!['localhost', '127.0.0.1'].includes(connection.hostname) || !connection.pathname.includes('test')) throw new Error('Use PostgreSQL local de teste.')
  if (!['localhost', '127.0.0.1'].includes(new URL(baseURL).hostname)) throw new Error('Use um site local de teste.')
  if (!process.env.JWT_SECRET) throw new Error('Defina o segredo JWT de teste.')
  const prisma = new PrismaClient()
  const version = `privacy-${randomUUID()}`
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const terms = await prisma.termosUso.findFirstOrThrow({ orderBy: { id: 'desc' } })
    const privacy = await prisma.politicaPrivacidade.findFirstOrThrow({ orderBy: { id: 'desc' } })
    const admin = await prisma.usuario.findUniqueOrThrow({ where: { email: 'cybereduca.oficial@gmail.com' } })
    const context = await browser.newContext({ baseURL, viewport: { width: 1365, height: 900 } })
    await context.addCookies([{ name: 'cybereduca_session', value: new JwtService({ secret: process.env.JWT_SECRET }).sign({ sub: admin.id }), url: baseURL, httpOnly: true }])
    const page = await context.newPage()
    page.setDefaultTimeout(30000)
    await page.goto('/admin/termos')
    await page.locator('#terms-section-title-0').waitFor()
    assert.equal(await page.locator('#terms-panel .terms-editor-section').count(), 11)
    const draftTitle = (await page.locator('#terms-section-title-0').inputValue()) + ' teste'
    await page.locator('#terms-section-title-0').fill(draftTitle)
    await page.getByRole('tab', { name: 'Privacidade e LGPD', exact: true }).click()
    await page.locator('#privacy-section-title-0').waitFor()
    assert.equal(await page.locator('#privacy-panel .terms-editor-section').count(), 13)
    assert.equal(await page.locator('#privacy-section-title-0').inputValue(), 'Responsável e contato')
    assert.equal(await page.getByRole('button', { name: 'Texto completo', exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Pré-visualizar', exact: true }).count(), 0)
    if (process.env.TERMS_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.TERMS_SCREENSHOT_DIR}/admin-privacidade.png` })
    await page.getByRole('tab', { name: 'Termos de Uso', exact: true }).click()
    assert.equal(await page.locator('#terms-section-title-0').inputValue(), draftTitle)
    await page.getByRole('tab', { name: 'Privacidade e LGPD', exact: true }).click()
    await page.locator('#privacy-version').fill(version)
    await page.getByRole('button', { name: 'Adicionar seção', exact: true }).click()
    await page.locator('#privacy-section-title-13').fill('Nova seção de privacidade')
    await page.locator('#privacy-section-content-13').fill('Texto da nova secao.\n\n' + 'palavralonga'.repeat(60))
    await page.getByRole('button', { name: 'Publicar nova versão', exact: true }).click()
    await page.getByText(`Versão ${version} publicada com sucesso.`, { exact: true }).waitFor()
    assert.equal((await prisma.termosUso.findFirstOrThrow({ orderBy: { id: 'desc' } })).conteudo, terms.conteudo)
    assert.equal((await prisma.termosUso.findFirstOrThrow({ orderBy: { id: 'desc' } })).versao, terms.versao)
    assert.equal((await prisma.politicaPrivacidade.findUniqueOrThrow({ where: { versao: privacy.versao } })).conteudo, privacy.conteudo)
    console.log('Chrome: abas, secoes, rascunhos e publicacao independente de privacidade verificados.')
    await context.clearCookies({ name: 'cybereduca_session' })
    await page.goto('/politicas')
    await page.getByRole('heading', { name: /Nova seção de privacidade/ }).waitFor()
    assert.equal(await page.locator('#termos-de-uso .legal-card').count(), 11)
    assert.equal(await page.locator('#politica-de-privacidade .legal-card').count(), 14)
    assert.equal(await page.locator('.legal-index a[href="#controlador"]').count(), 1)
    assert.equal(await page.locator('.legal-index a[href="#privacidade-nova-secao-de-privacidade"]').count(), 1)
    const ids = await page.locator('.legal-card').evaluateAll(cards => cards.map(card => card.id))
    assert.equal(new Set(ids).size, ids.length)
    for (const width of [1365, 390]) {
      await page.setViewportSize({ width, height: 900 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
    }
    const latest = await prisma.politicaPrivacidade.findFirstOrThrow({ orderBy: { id: 'desc' } })
    assert.equal(await page.locator('.legal-footer time').getAttribute('datetime'), latest.publicadoEm.toISOString())
    await context.close()
    console.log('Chrome: grupos separados, novo card, indice, rodape e layout responsivo verificados.')
  } finally {
    await browser.close()
    await prisma.politicaPrivacidade.deleteMany({ where: { versao: version } })
    await prisma.termosUso.deleteMany({ where: { versao: version } })
    await prisma.$disconnect()
  }
}

main().catch(error => { console.error(error.stack); process.exitCode = 1 })
