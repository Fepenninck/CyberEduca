const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { chromium } = require('playwright-core')
const { PrismaClient } = require('../../backend/node_modules/@prisma/client')
const { JwtService } = require('../../backend/node_modules/@nestjs/jwt')

async function main() {
  const baseURL = process.env.PRIVACY_TEST_URL || 'http://localhost:3301'
  const database = new URL(process.env.DATABASE_URL || '')
  if (!['127.0.0.1', 'localhost'].includes(database.hostname) || !database.pathname.includes('test')) throw new Error('Use somente PostgreSQL local de teste.')
  if (!['127.0.0.1', 'localhost'].includes(new URL(baseURL).hostname)) throw new Error('Use somente um site local de teste.')
  if (!process.env.JWT_SECRET) throw new Error('Defina o segredo JWT do servidor de teste.')
  const prisma = new PrismaClient()
  const jwt = new JwtService({ secret: process.env.JWT_SECRET })
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1365, height: 900 } })
  const page = await context.newPage()
  page.setDefaultTimeout(30000)
  const suffix = randomUUID()
  const email = `browser-${suffix}@example.test`
  const googleEmail = `google-${suffix}@example.test`
  const session = async user => context.addCookies([{ name: 'cybereduca_session', value: jwt.sign({ sub: user.id }), url: baseURL, httpOnly: true, sameSite: 'Lax' }])
  try {
    await page.goto('/cadastro')
    await page.getByRole('button', { name: 'Rejeitar', exact: true }).click()
    assert.equal((await context.cookies()).find(c => c.name === 'cybereduca_cookie_consent').value, 'v2-essential')
    await page.reload()
    await page.getByRole('button', { name: 'Preferências de cookies', exact: true }).click()
    await page.getByRole('button', { name: 'Aceitar', exact: true }).click()
    await page.evaluate(() => {
      localStorage.setItem('cybereduca-achievement:teste:conquista', 'shown')
      localStorage.setItem('preservar-teste', 'ok')
    })
    await page.getByRole('button', { name: 'Preferências de cookies', exact: true }).click()
    await page.getByRole('button', { name: 'Rejeitar', exact: true }).click()
    assert.equal(await page.evaluate(() => localStorage.getItem('cybereduca-achievement:teste:conquista')), null)
    assert.equal(await page.evaluate(() => localStorage.getItem('preservar-teste')), 'ok')
    assert.equal((await context.cookies()).find(c => c.name === 'cybereduca_cookie_consent').value, 'v2-essential')
    console.log('Chrome: aceite, persistencia e revogacao de cookies passaram.')

    await page.locator('#name').fill(' ')
    await page.getByRole('button', { name: 'Criar conta', exact: true }).click({ force: true })
    await page.locator('#name-error').waitFor()
    await page.locator('#name').fill('  Aluno Browser  ')
    await page.locator('#signup-email').fill(email)
    await page.locator('#signup-password').fill('Senha123!')
    await page.locator('#confirm-password').fill('Senha123!')
    await page.getByRole('button', { name: 'Criar conta', exact: true }).click({ force: true })
    await page.locator('.signup-terms-error').waitFor()
    assert.equal(await prisma.usuario.count({ where: { email } }), 0)
    await page.locator('.signup-terms input').check()
    await page.getByRole('button', { name: 'Criar conta', exact: true }).click({ force: true })
    await page.waitForURL('**/login')
    const aluno = await prisma.usuario.findUniqueOrThrow({ where: { email } })
    assert.equal(aluno.nome, 'Aluno Browser')
    assert.equal(aluno.termosVersao, '2026-11-21')
    assert.ok(aluno.termosAceitosEm instanceof Date)
    console.log('Chrome: cadastro exige nome valido e aceite, com registro no PostgreSQL.')

    await page.goto('/admin/usuarios')
    await page.waitForURL('**/login')
    await session(aluno)
    await page.goto('/admin/usuarios')
    await page.waitForURL('**/login')
    assert.equal((await context.request.get('/api/admin/usuarios')).status(), 403)
    const admin = await prisma.usuario.findUniqueOrThrow({ where: { email: 'cybereduca.oficial@gmail.com' } })
    await session(admin)
    await page.goto('/admin/usuarios')
    await page.getByText('Aluno Browser', { exact: true }).waitFor()
    assert.ok((await page.locator('body').innerText()).includes('br***@example.test'))
    assert.ok(!(await page.locator('body').innerText()).includes(email))
    console.log('Chrome: visitante e aluno sem acesso administrativo; administrador recebe email mascarado.')

    await context.clearCookies({ name: 'cybereduca_session' })
    const google = await prisma.usuario.create({ data: { nome: 'Google Browser', email: googleEmail, googleId: suffix } })
    await context.addCookies([{ name: 'cybereduca_termos_pendentes', value: jwt.sign({ sub: google.id, purpose: 'aceite-termos' }, { audience: 'aceite-termos', expiresIn: '10m' }), url: baseURL, httpOnly: true, sameSite: 'Lax' }])
    await page.goto('/aceitar-termos')
    const aceitar = page.getByRole('button', { name: 'Aceitar e continuar', exact: true })
    assert.equal(await aceitar.isDisabled(), true)
    await page.getByRole('checkbox').check()
    await aceitar.click()
    await page.waitForURL('**/dashboard')
    const aceito = await prisma.usuario.findUniqueOrThrow({ where: { id: google.id } })
    assert.equal(aceito.termosVersao, '2026-11-21')
    assert.ok(aceito.termosAceitosEm)
    console.log('Chrome: tela de aceite Google so libera a sessao apos confirmacao.')

    await session(aluno)
    await page.goto('/configuracoes')
    await page.getByRole('button', { name: 'Excluir minha conta', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const excluir = dialog.getByRole('button', { name: 'Excluir minha conta', exact: true })
    assert.equal(await excluir.isDisabled(), true)
    await dialog.locator('input').fill('EXCLUIR')
    assert.equal(await excluir.isDisabled(), true)
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
    assert.ok(await prisma.usuario.findUnique({ where: { id: aluno.id } }))
    await page.getByRole('button', { name: 'Excluir minha conta', exact: true }).click()
    await dialog.locator('input').fill('excluir')
    await excluir.click()
    await page.waitForURL('**/login?conta=excluida')
    assert.equal(await prisma.usuario.findUnique({ where: { id: aluno.id } }), null)
    assert.equal((await context.cookies()).some(c => c.name === 'cybereduca_session'), false)
    console.log('Chrome: confirmacao, cancelamento, exclusao real e encerramento da sessao passaram.')
  } finally {
    await context.close()
    await browser.close()
    const users = await prisma.usuario.findMany({ where: { email: { in: [email, googleEmail] } }, select: { id: true } })
    await prisma.logAuditoria.deleteMany({ where: { OR: [{ atorId: { in: users.map(u => u.id) } }, { entidadeId: { in: users.map(u => u.id) } }] } })
    await prisma.usuario.deleteMany({ where: { email: { in: [email, googleEmail] } } })
    await prisma.$disconnect()
  }
}

main().catch(error => { console.error(error.message); process.exitCode = 1 })
