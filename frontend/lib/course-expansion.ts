export function expandCourses(courses: LibraryCourse[]) {
  for (const course of courses) {
    const extra = units[course.id.replace("biblioteca-", "")] || [];
    for (const [i, unit] of extra.entries()) {
      const index = course.lessons.length;
      const reverse = index % 2 === 1;
      const lesson: LibraryLesson = {
        id: `aula-${index + 1}`,
        title: unit[0],
        concept: unit[1],
        practice: unit[3],
        question: `Na aplicação de “${unit[0]}”, qual decisão é adequada?`,
        options: reverse ? [unit[5], unit[4]] : [unit[4], unit[5]],
        correct: reverse ? 1 : 0,
        explanation: unit[6],
        source: course.lessons[0].source,
        sourceTitle: course.lessons[0].sourceTitle,
        caseStudy: unit[2],
        expected: unit[6],
        objectives: [
          `Explicar ${unit[0].toLowerCase()}.`,
          "Aplicar o conceito a um caso e justificar a decisão.",
          "Produzir e revisar a entrega prática proposta.",
        ],
      };
      course.lessons.push(lesson);
    }
  }
}
